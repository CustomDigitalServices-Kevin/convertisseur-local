import { describe, expect, it } from "vitest";
import { decodeBmp, encodeBmp } from "./bmp";
import { detectFormat } from "../../core/detect";
import { loadImageFixture } from "./test-fixtures";
import { expectConversionErrorCode } from "../data/test-helpers";

// Pure decode/encode coverage only, same reasoning as tiff.test.ts's header
// comment: no OffscreenCanvas involved, but the full bmp<->png/jpeg
// module.ts pipeline needs one and is deferred to the E2E suite (task 12).

describe("decodeBmp", () => {
  it("decodes tests/fixtures/tiny.bmp (generated by bmp-js itself) to a 2x2 RGBA image", () => {
    const image = decodeBmp(loadImageFixture("tiny.bmp"));
    expect(image.width).toBe(2);
    expect(image.height).toBe(2);
    // row0 = red, green; row1 = blue, white (see generate.mjs's abgr bytes).
    // 24bit BMP carries no alpha: bmp-js hardcodes the decoded byte to 0,
    // which decodeBmp must read as fully opaque (255), not transparent.
    expect(Array.from(image.data)).toEqual([
      255, 0, 0, 255, 0, 255, 0, 255, 0, 0, 255, 255, 255, 255, 255, 255,
    ]);
  });

  it("throws corrupted-file for a non-BMP buffer", () => {
    const garbage = new TextEncoder().encode("not a bmp file at all").buffer;
    expectConversionErrorCode(() => decodeBmp(garbage), "corrupted-file");
  });
});

describe("encodeBmp", () => {
  it("produces bytes detectFormat recognizes as bmp", () => {
    const image = new ImageData(
      new Uint8ClampedArray([255, 0, 0, 255, 0, 255, 0, 255, 0, 0, 255, 255, 255, 255, 255, 255]),
      2,
      2,
    );
    const encoded = encodeBmp(image);
    expect(detectFormat("out.bmp", encoded)).toBe("bmp");
  });

  it("round-trips RGB through decodeBmp losslessly, alpha forced to 255", () => {
    const original = new ImageData(
      new Uint8ClampedArray([10, 20, 30, 255, 40, 50, 60, 255, 70, 80, 90, 255, 100, 110, 120, 255]),
      2,
      2,
    );
    const decoded = decodeBmp(encodeBmp(original));
    expect(decoded.width).toBe(2);
    expect(decoded.height).toBe(2);
    expect(Array.from(decoded.data)).toEqual(Array.from(original.data));
  });
});
