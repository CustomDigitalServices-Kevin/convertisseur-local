import { describe, expect, it } from "vitest";
import { decodeGif, encodeGif } from "./gif";
import { detectFormat } from "../../core/detect";
import { loadImageFixture } from "./test-fixtures";
import { expectConversionErrorCode } from "../data/test-helpers";

// Pure decode/encode coverage only, same reasoning as tiff.test.ts's header
// comment: no OffscreenCanvas involved here, but the full
// gif<->png/webp module.ts pipeline needs one and is deferred to the E2E
// suite (task 12).

describe("decodeGif", () => {
  it("decodes tests/fixtures/tiny.gif (generated by gifenc) to a 2x2 RGBA image", () => {
    const image = decodeGif(loadImageFixture("tiny.gif"));
    expect(image.width).toBe(2);
    expect(image.height).toBe(2);
    expect(image.data).toHaveLength(16);
    // 4 distinct opaque colors in: alpha must always come back 255 (GIF has
    // no per-pixel alpha in this encoder's output, only optional 1-bit
    // transparency, which encodeGif never enables).
    for (let i = 3; i < image.data.length; i += 4) {
      expect(image.data[i]).toBe(255);
    }
  });

  it("throws corrupted-file for a non-GIF buffer", () => {
    const garbage = new TextEncoder().encode("not a gif file at all").buffer;
    expectConversionErrorCode(() => decodeGif(garbage), "corrupted-file");
  });
});

describe("encodeGif", () => {
  it("produces bytes detectFormat recognizes as gif", () => {
    const image = new ImageData(
      new Uint8ClampedArray([255, 0, 0, 255, 0, 255, 0, 255, 0, 0, 255, 255, 255, 255, 255, 255]),
      2,
      2,
    );
    const encoded = encodeGif(image);
    expect(detectFormat("out.gif", encoded)).toBe("gif");
  });

  it("round-trips a small solid-color palette through decodeGif losslessly", () => {
    const original = new ImageData(
      new Uint8ClampedArray([255, 0, 0, 255, 0, 255, 0, 255, 0, 0, 255, 255, 255, 255, 255, 255]),
      2,
      2,
    );
    const decoded = decodeGif(encodeGif(original));
    expect(decoded.width).toBe(2);
    expect(decoded.height).toBe(2);
    expect(Array.from(decoded.data)).toEqual(Array.from(original.data));
  });
});
