import { describe, expect, it } from "vitest";
import { decodeTiff, encodeTiff } from "./tiff";
import { detectFormat } from "../../core/detect";
import { loadImageFixture } from "./test-fixtures";
import { expectConversionErrorCode } from "../data/test-helpers";

// This file covers tiff.ts's pure decode/encode functions only (no
// OffscreenCanvas involved -- both are plain-JS via utif, unlike the
// browser-only createImageBitmap/convertToBlob path in canvas.ts). The full
// tiff<->png/jpeg/webp module.ts pipeline needs a real OffscreenCanvas and
// is deferred to the E2E suite (task 12), same as avif/svg already are per
// module.test.ts's header comment.

describe("decodeTiff", () => {
  it("decodes tests/fixtures/tiny.tiff (generated by utif itself) to the expected 2x2 RGBA image", () => {
    const image = decodeTiff(loadImageFixture("tiny.tiff"));
    expect(image.width).toBe(2);
    expect(image.height).toBe(2);
    // row0 = red, green; row1 = blue, white (see generate.mjs's RGBA_2X2)
    expect(Array.from(image.data)).toEqual([
      255, 0, 0, 255, 0, 255, 0, 255, 0, 0, 255, 255, 255, 255, 255, 255,
    ]);
  });

  it("throws corrupted-file for a non-TIFF buffer", () => {
    const garbage = new TextEncoder().encode("not a tiff file at all").buffer;
    expectConversionErrorCode(() => decodeTiff(garbage), "corrupted-file");
  });
});

describe("encodeTiff", () => {
  it("produces bytes detectFormat recognizes as tiff", () => {
    const image = new ImageData(
      new Uint8ClampedArray([255, 0, 0, 255, 0, 255, 0, 255, 0, 0, 255, 255, 255, 255, 255, 255]),
      2,
      2,
    );
    const encoded = encodeTiff(image);
    expect(detectFormat("out.tiff", encoded)).toBe("tiff");
  });

  it("round-trips through decodeTiff with identical pixels", () => {
    const original = new ImageData(
      new Uint8ClampedArray([10, 20, 30, 255, 40, 50, 60, 255, 70, 80, 90, 255, 100, 110, 120, 255]),
      2,
      2,
    );
    const decoded = decodeTiff(encodeTiff(original));
    expect(decoded.width).toBe(2);
    expect(decoded.height).toBe(2);
    expect(Array.from(decoded.data)).toEqual(Array.from(original.data));
  });
});
